import unittest
from unittest.mock import patch

from flask.config import Config

original_from_object = Config.from_object


def test_config(config, obj):
    original_from_object(config, obj)
    config.update(SQLALCHEMY_DATABASE_URI='sqlite://', TESTING=True)


with patch.object(Config, 'from_object', test_config):
    from keywoo import app, db
    from keywoo.models.users import User
    from keywoo.passwords import check_password_hash, generate_password_hash

from werkzeug.security import generate_password_hash as werkzeug_generate_password_hash


class AuthenticationTests(unittest.TestCase):
    def setUp(self):
        self.context = app.app_context()
        self.context.push()
        db.create_all()
        self.client = app.test_client()

    def tearDown(self):
        db.session.remove()
        db.drop_all()
        self.context.pop()

    def add_user(self, password_hash):
        user = User(name='alice', password=password_hash)
        db.session.add(user)
        db.session.commit()
        return user

    def test_database_startup_command(self):
        from click.testing import CliRunner
        from manage import manager
        result = CliRunner().invoke(manager, ["init_db"])
        self.assertEqual(result.exit_code, 0, result.output)

    def test_signup_and_login(self):
        response = self.client.post('/signup', data={'name': 'alice', 'password': 'secret'})
        self.assertEqual(response.location, '/login')
        user = User.query.one()
        self.assertLessEqual(len(user.password), 100)
        self.assertTrue(check_password_hash(user.password, 'secret'))
        self.assertFalse(check_password_hash(user.password, 'wrong'))
        response = self.client.post('/login', data={'name': 'alice', 'password': 'secret'})
        self.assertEqual(response.location, '/')

    def test_legacy_login_upgrades_only_after_success(self):
        # Format generated by Werkzeug's historical salted sha256 method.
        # Fixture generated with Werkzeug 1.0.1, independently of this verifier.
        legacy = 'sha256$KolxR4IU$8ae46b7f69379b93938ac13c13415676046d09d642208a3ae7dea94bf6a7e8cb'
        user = self.add_user(legacy)
        for password in ('wrong', None):
            data = {'name': 'alice'}
            if password is not None:
                data['password'] = password
            self.assertEqual(self.client.post('/login', data=data).location, '/login')
            self.assertEqual(user.password, legacy)
        self.assertEqual(self.client.post('/login', data={'name': 'alice', 'password': 'secret'}).location, '/')
        db.session.expire_all()
        upgraded = User.query.one().password
        self.assertTrue(upgraded.startswith('pbkdf2:sha256:'))
        self.assertLessEqual(len(upgraded), 100)
        self.assertTrue(check_password_hash(upgraded, 'secret'))

    def test_supported_hashes_are_preserved(self):
        for method in ('pbkdf2:sha256:1000', 'scrypt'):
            with self.subTest(method=method):
                encoded = werkzeug_generate_password_hash('secret', method=method)
                user = self.add_user(encoded)
                self.assertEqual(self.client.post('/login', data={'name': 'alice', 'password': 'wrong'}).location, '/login')
                self.assertEqual(self.client.post('/login', data={'name': 'alice', 'password': 'secret'}).location, '/')
                self.assertEqual(user.password, encoded)
                db.session.delete(user)
                db.session.commit()

    def test_malformed_legacy_hashes_are_rejected(self):
        for encoded in ('sha256$', 'sha256$$abc', 'sha256$salt$abc$extra'):
            self.assertFalse(check_password_hash(encoded, 'secret'))


if __name__ == '__main__':
    unittest.main()
